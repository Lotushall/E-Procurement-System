<?php

namespace App\Console\Commands;

use Nwidart\Modules\Commands\Make\ModuleMakeCommand as BaseModuleMakeCommand;

class ModuleMakeCommand extends BaseModuleMakeCommand
{
    /**
     * Execute the console command.
     */
    public function handle(): int
    {
        $code = parent::handle();

        if ($code !== 0) {
            return $code;
        }

        foreach ($this->argument('name') as $module) {
            foreach ($this->entityCommands($module) as [$command, $arguments]) {
                $subCode = $this->call($command, $arguments);

                if ($subCode !== 0) {
                    return $subCode;
                }
            }
        }

        return 0;
    }

    /**
     * Sub-commands that scaffold the primary entity (same name as the module):
     * Model, Repository, RepositoryInterface, and Store/Update Requests.
     * The Controller is already generated by parent::handle() (generator.controller.generate = true).
     *
     * @return array<int, array{0: string, 1: array<string, string>}>
     */
    protected function entityCommands(string $module): array
    {
        return [
            ['module:make-model', ['model' => $module, 'module' => $module]],
            ['module:make-repository', ['name' => "{$module}Repository", 'module' => $module]],
            ['module:make-interface', ['name' => "{$module}RepositoryInterface", 'module' => $module]],
            ['module:make-request', ['name' => "Store{$module}Request", 'module' => $module]],
            ['module:make-request', ['name' => "Update{$module}Request", 'module' => $module]],
        ];
    }
}
